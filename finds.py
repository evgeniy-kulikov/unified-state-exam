# Число делится на 4 тогда, когда число, образованное его двумя последними цифрами, делится на 4,
# или если оно оканчивается двумя нулями

# Функция math.gcd() в Python используется для нахождения наибольшего общего делителя (НОД) целых чисел
from math import gcd
print(gcd(54, 24))  # 6
print(gcd(54, 0))  # 54
print(gcd(54, 108, 216))  #  54
print(gcd(0, 0))  # 0

""" Наименьшее общее кратное """
# начиная с версии Python 3.9
from math import lcm
print(lcm(14, 21))  # 42
print(lcm(4, 6, 8))  # 24