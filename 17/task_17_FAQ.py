"""
Преобразование числа в двоичную, восьмеричную и шестнадцатеричную  систему счисления внутри f-строки 
(Python 3.6+)
"""
n = 10
n2 = f'{n:b}'  # '1010'
n8 = f'{n:o}'  # '12'
n16 = f'{n:x}'  # 'a'
n16 = f'{n:X}'  # 'A'

# С префиксом
n2 = f'{n:#b}'  # '0b1010'
n8 = f'{n:#o}'  # '0o12'
n16 = f'{n:#x}'  # '0xa'
n16 = f'{n:#X}'  # '0xA'


